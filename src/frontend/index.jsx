import React, { useState } from 'react';
import ForgeReconciler, {
  Box,
  Inline,
  Stack,
  Text,
  Strong,
  Heading,
  Button,
  Textfield,
  Label,
  Lozenge,
  Link,
  Spinner,
  SectionMessage,
  ProgressBar,
} from '@forge/react';
import { invoke } from '@forge/bridge';

const SEV_APPEARANCE = { high: 'removed', medium: 'moved', low: 'default' };

function Stat({ label, value }) {
  return (
    <Box padding="space.100" backgroundColor="color.background.neutral" xcss={{ borderRadius: 'border.radius' }}>
      <Stack alignInline="center" space="space.0">
        <Heading as="h2">{value}</Heading>
        <Text size="small">{label}</Text>
      </Stack>
    </Box>
  );
}

const CONF_APPEARANCE = { high: 'success', medium: 'moved', low: 'removed' };
const CONF_LABEL = { high: 'On track', medium: 'At risk', low: 'Off track' };

function ConfidenceCard({ forecast }) {
  const f = forecast;
  return (
    <Box padding="space.200" backgroundColor="color.background.neutral" xcss={{ borderRadius: 'border.radius' }}>
      <Stack space="space.100">
        <Inline space="space.100" alignBlock="center" shouldWrap>
          <Text><Strong>Sprint confidence</Strong></Text>
          <Lozenge appearance={CONF_APPEARANCE[f.confidence] || 'default'} isBold>
            {f.confidence.toUpperCase()} · {CONF_LABEL[f.confidence]}
          </Lozenge>
          {f.projectedCompletionPercent != null && (
            <Text>Projected {f.projectedCompletionPercent}% done by the end date</Text>
          )}
        </Inline>
        <Stack space="space.0">
          {f.drivers.map((d, i) => (
            <Text key={i} size="small">• {d}</Text>
          ))}
        </Stack>
      </Stack>
    </Box>
  );
}

function Report({ res }) {
  const { sprint, report } = res;
  const s = report.summary;
  const findings = report.findings.slice(0, 12);

  return (
    <Stack space="space.300">
      <Box>
        <Heading as="h2">{sprint.name}</Heading>
        {sprint.endDate && <Text size="small">Ends {sprint.endDate.slice(0, 10)}</Text>}
      </Box>

      {report.forecast && <ConfidenceCard forecast={report.forecast} />}

      <Inline space="space.100" shouldWrap>
        <Stat label="Done" value={`${s.completionPercent}%`} />
        <Stat label="In progress" value={s.inProgress} />
        <Stat label="To do" value={s.toDo} />
        <Stat label="At risk" value={s.atRiskIssues} />
      </Inline>

      <Box>
        <Text size="small">Completion: {s.done}/{s.total} issues</Text>
        <ProgressBar value={s.total > 0 ? s.done / s.total : 0} />
      </Box>

      <Inline space="space.100" shouldWrap>
        <Lozenge appearance="removed">{s.findingsBySeverity.high} high</Lozenge>
        <Lozenge appearance="moved">{s.findingsBySeverity.medium} medium</Lozenge>
        <Lozenge appearance="default">{s.findingsBySeverity.low} low</Lozenge>
      </Inline>

      <Box>
        <Heading as="h3">Top risks</Heading>
        {findings.length === 0 && <Text>No risks detected. 🎉</Text>}
        <Stack space="space.100">
          {findings.map((f, i) => (
            <Inline key={i} space="space.100" alignBlock="center" shouldWrap>
              <Lozenge appearance={SEV_APPEARANCE[f.severity] || 'default'}>{f.severity}</Lozenge>
              {f.url ? (
                <Link href={f.url} openNewTab>{f.key}</Link>
              ) : (
                <Strong>{f.key}</Strong>
              )}
              <Text>{f.reason}</Text>
            </Inline>
          ))}
        </Stack>
      </Box>

      <Box>
        <Heading as="h3">Workload</Heading>
        <Stack space="space.050">
          {report.load.length === 0 && <Text>Nobody has work in progress.</Text>}
          {report.load.map((r, i) => (
            <Text key={i}>
              <Strong>{r.assignee}</Strong>: {r.inProgress} in progress
              {r.storyPoints ? ` · ${r.storyPoints} pts` : ''}
              {r.overloaded ? ' — ⚠ over WIP limit' : ''}
            </Text>
          ))}
        </Stack>
      </Box>

      <Box>
        <Heading as="h3">Blocked</Heading>
        <Stack space="space.050">
          {report.blocked.length === 0 && <Text>Nothing is blocked.</Text>}
          {report.blocked.map((b, i) => (
            <Text key={i}>
              {b.url ? <Link href={b.url} openNewTab>{b.key}</Link> : <Strong>{b.key}</Strong>}
              {b.flagged ? ' — flagged as an impediment' : ''}
              {b.blockedBy.length ? ` — blocked by ${b.blockedBy.join(', ')}` : ''}
            </Text>
          ))}
        </Stack>
      </Box>

      <Text size="small">Every number above is computed by a unit-tested engine from live Jira data — not generated by an AI.</Text>
    </Stack>
  );
}

function App() {
  const [boardId, setBoardId] = useState('');
  const [loading, setLoading] = useState(false);
  const [res, setRes] = useState(null);

  const analyze = async () => {
    setLoading(true);
    setRes(null);
    try {
      const r = await invoke('getSprintReport', { boardId });
      setRes(r);
    } catch (e) {
      setRes({ error: String(e && e.message ? e.message : e) });
    }
    setLoading(false);
  };

  return (
    <Stack space="space.300">
      <Box>
        <Heading as="h1">Sprint Sentinel</Heading>
        <Text>Evidence-backed sprint health for your Jira board — what is at risk, who is overloaded, and what is blocked. Every finding cites the issue it came from.</Text>
      </Box>

      <Inline space="space.100" alignBlock="end" shouldWrap>
        <Stack space="space.050">
          <Label labelFor="boardId">Board id</Label>
          <Textfield
            id="boardId"
            placeholder="e.g. 211"
            onChange={(e) => setBoardId(e.target.value)}
          />
        </Stack>
        <Button appearance="primary" onClick={analyze} isDisabled={loading}>Analyze sprint</Button>
      </Inline>

      {loading && <Spinner label="Reading the live sprint…" />}

      {res && res.error && (
        <SectionMessage appearance="error" title="Could not analyze">
          <Text>{res.error}</Text>
        </SectionMessage>
      )}

      {res && !res.error && res.sprint === null && (
        <SectionMessage appearance="warning" title="No active sprint">
          <Text>No active sprint was found for board {res.boardId}. Start a sprint or check the board id.</Text>
        </SectionMessage>
      )}

      {res && res.report && <Report res={res} />}
    </Stack>
  );
}

ForgeReconciler.render(
  <React.StrictMode>
    <App />
  </React.StrictMode>,
);
